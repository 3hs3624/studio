\set ON_ERROR_STOP on
\getenv app_password APP_PASSWORD
\getenv migration_password MIGRATION_PASSWORD
CREATE ROLE itsm_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'migration_password';
CREATE ROLE itsm_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
REVOKE ALL ON DATABASE itsm_local FROM PUBLIC;
GRANT CONNECT ON DATABASE itsm_local TO itsm_migrator, itsm_runtime;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO itsm_migrator;
GRANT USAGE ON SCHEMA public TO itsm_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE itsm_migrator IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO itsm_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE itsm_migrator IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO itsm_runtime;
